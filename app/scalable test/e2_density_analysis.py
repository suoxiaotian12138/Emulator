    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(tiers, tor_p95, marker="o", label="Tor build p95")
    ax.plot(tiers, tor_p99, marker="o", linestyle="--", label="Tor build p99")
    ax.plot(tiers, torbox_p95, marker="s", label="Torbox build p95")
    ax.plot(tiers, torbox_p99, marker="s", linestyle="--", label="Torbox build p99")

    ax.set_xlabel("Relay tier (node scale)")
    ax.set_ylabel("Build time (ms)")
    ax.set_title("Tail build-time vs node scale (p95/p99)")
    ax.grid(True, linestyle="--", alpha=0.3)
    ax.legend()

    out_path = out_dir / "build_tail_p95_p99.png"
    fig.tight_layout()
    fig.savefig(out_path, dpi=160)
    plt.close(fig)
    return out_path


