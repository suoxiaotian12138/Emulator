def plot_total_memory(out_dir: Path, runs: List[RunSummary]) -> Optional[Path]:
    # --- 1. 数据提取与清洗 ---
    by_mode: Dict[str, Dict[str, RunSummary]] = {}
    for run in runs:
        by_mode.setdefault(run.mode_tag, {})[run.relay_tier] = run

    tiers = _sort_tiers(
        set(by_mode.get("tor", {}).keys()) | set(by_mode.get("torbox", {}).keys())
    )
    if not tiers:
        return None

    def collect(mode: str) -> List[Optional[float]]:
        return [getattr(by_mode.get(mode, {}).get(tier), "peak_mem_mb", None) for tier in tiers]

    tor_mem = collect("tor")
    torbox_mem = collect("torbox")

    # X轴数值化：尝试将 "10", "20" 转为数字，以保证横轴比例真实
    try:
        x_numeric = np.array([float(t) for t in tiers])
        is_numeric_x = True
    except ValueError:
        x_numeric = np.arange(len(tiers))
        is_numeric_x = False

    def clean_xy(y_data):
        valid_idx = [i for i, v in enumerate(y_data) if v is not None]
        return x_numeric[valid_idx], np.array([y_data[i] for i in valid_idx])

    x_tor, y_tor = clean_xy(tor_mem)
    x_torbox, y_torbox = clean_xy(torbox_mem)

    # --- 2. 论文级绘图设置 ---

    # 字体配置：优先使用 Arial/Helvetica 等无衬线字体，清晰度高
    plt.rcParams['font.family'] = 'sans-serif'
    plt.rcParams['font.sans-serif'] = ['Arial', 'DejaVu Sans', 'Helvetica', 'sans-serif']

    # 画布大小：(8, 5) 是一个适合插入论文的标准比例
    fig, ax = plt.subplots(figsize=(8, 5))

    # 配色方案：高对比度，科研常用色 (深蓝 vs 砖红)
    # 这种配色在转为灰度图时灰度值差异也较大，便于识别
    c_tor = '#0072B2'  # Blue
    c_torbox = '#D55E00'  # Vermilion (Red-Orange)

    # --- 3. 绘制折线 (保持真实数据，不做插值) ---

    # Tor 线条
    ax.plot(x_tor, y_tor,
            marker='o',  # 圆形标记
            markersize=8,  # 标记大小：适中，缩放后依然可见
            linewidth=2.0,  # 线宽：2.0 打印清晰
            color=c_tor,
            label="Tor",  # 简化图例标签，去掉 "Peak Memory" 冗余词
            markeredgecolor='white',  # 白边提升对比度
            markeredgewidth=1.5,
            zorder=3)

    # Torbox 线条
    ax.plot(x_torbox, y_torbox,
            marker='s',  # 方形标记 (形状不同，便于黑白区分)
            markersize=8,
            linewidth=2.0,
            color=c_torbox,
            label="Torbox",
            markeredgecolor='white',
            markeredgewidth=1.5,
            zorder=3)

    # --- 4. 样式精修 ---

    # 坐标轴标签：字号 14，加粗
    ax.set_xlabel("Relay Tier (Node Scale)", fontsize=14, fontweight='bold', labelpad=8)
    ax.set_ylabel("Peak Memory (MB)", fontsize=14, fontweight='bold', labelpad=8)

    # 刻度标签：字号 12
    ax.tick_params(axis='both', which='major', labelsize=12, width=1.2, length=5)

    # 还原 X 轴的文本标签 (如果是数值轴)
    if is_numeric_x:
        ax.set_xticks(x_numeric)
        ax.set_xticklabels(tiers)

    # Y 轴范围：从 0 开始，顶部留出 10% 空间
    y_max = max(np.max(y_tor) if len(y_tor) else 0, np.max(y_torbox) if len(y_torbox) else 0)
    ax.set_ylim(0, y_max * 1.1)

    # 边框处理：典型的学术图表风格（去掉上、右边框）
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.spines['left'].set_linewidth(1.2)
    ax.spines['bottom'].set_linewidth(1.2)

    # 网格线：仅保留横向，灰色虚线，透明度低，位于底层
    ax.yaxis.grid(True, linestyle='--', color='gray', alpha=0.3, zorder=0)
    ax.xaxis.grid(False)

    # 图例：去框，字号 12，放在左上角
    ax.legend(frameon=False, fontsize=12, loc='upper left')

    # 保存配置
    out_path = out_dir / "total_memory_overhead.png"

    # tight_layout 确保文字不被裁剪
    fig.tight_layout()

    # dpi=300 是印刷出版的标准分辨率
    fig.savefig(out_path, dpi=300, bbox_inches='tight')
    plt.close(fig)

    return out_path



def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Analyze E2 circuit density logs for scaling and tail latency.",
    )
    parser.add_argument(
        "--log-root",
        type=Path,
        default=Path("exp") / "deployment" / "e2_density" / "logs",
        help="Root directory containing mode_tag/relay_tier/run_meta.json",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("exp") / "deployment" / "e2_density" / "analysis",
        help="Directory to store CSV summaries and plots",
    )
    parser.add_argument(
        "--meta",
        type=Path,
        nargs="*",
        default=[],
        help="Optional explicit run_meta.json paths",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    runs = discover_runs(args.log_root, args.meta)
    if not runs:
        print("No runs discovered. Check --log-root or --meta paths.")
        return

    args.out_dir.mkdir(parents=True, exist_ok=True)
    summary_csv = write_summary_csv(args.out_dir, runs)
    overhead_csv = write_overhead_csv(args.out_dir, runs)
    overhead_plot = plot_overhead(args.out_dir, runs)
    tail_plot = plot_tail_build(args.out_dir, runs)
    resource_plot = plot_total_resources(args.out_dir, runs)
    memory_plot = plot_total_memory(args.out_dir, runs)

    print(f"Summary CSV: {summary_csv}")
    print(f"Overhead CSV: {overhead_csv}")
    if overhead_plot:
        print(f"Overhead plot: {overhead_plot}")
    if tail_plot:
        print(f"Tail build-time plot: {tail_plot}")
    if resource_plot:
        print(f"Total resource plot: {resource_plot}")
    if memory_plot:
        print(f"Total memory plot: {memory_plot}")


if __name__ == "__main__":
    main()